#!/usr/bin/env python3
"""make_tableM_tiers.py — formal family-stability tier table (registry §9 artifact).

Applies the registry §6 verdict combination to the Phase-M outputs and writes
manuscript/tables/tableM_tiers.md. The verdict logic is IMPORTED from
make_familyinvestigation_report.py so the verification report and this table can
never disagree.

Inputs (read-only): results/exM_suite_metrics.csv · results/exM_benchmark_matched_summary.csv
Output: manuscript/tables/tableM_tiers.md (atomic write)
Run: python3 code/make_tableM_tiers.py   (after any Phase-M recomputation)
"""
from __future__ import annotations
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "code"))
from make_familyinvestigation_report import (  # noqa: E402
    load, f, num, sci, pct, registry_status, TAU,
)

OUT = os.path.join(ROOT, "manuscript", "tables", "tableM_tiers.md")
# registry §10: F1a and F2 classify *provisional* under this battery while an earlier
# manuscript build published them as *incidental*. Reconciled 2026-10-21: the published
# manuscript carries no per-family tier verdicts, so there is no caption left to correct
# and the verdicts below are the classification of record. See the registry, §10.
RECONCILE = set()  # resolved 2026-10-21 — no family is flagged


def t1_mark(r):
    ratio, lo = f(r["paired_ratio_2d_pca"]), f(r["ci_low_2d_pca"])
    return "✓" if (ratio > 1 and lo > 1) else ("~" if ratio > 1 else "×")


def t2_mark(r):
    ratio, lo = f(r["paired_ratio_mds"]), f(r["ci_low_mds"])
    return "✓" if (ratio > 1 and lo > 1) else ("~" if ratio > 1 else "×")


def main():
    frozen_tier = {r["family"]: r["tier"] for r in load("family_tiers.csv")}
    suites = load("exM_suite_metrics.csv")
    t7 = {r["candidate"]: r for r in load("exM_benchmark_matched_summary.csv")}
    assert len(suites) == 16, len(suites)
    assert all(r["name"] in t7 for r in suites), "T7 summary incomplete"
    assert all(r["paired_ratio_2d_pca"] not in ("", None) and r["paired_ratio_mds"] not in ("", None)
               for r in suites), ("partial suite metrics (--pca-only run?) — run the full "
                                  "code/experiment_M_familyexpansion.py first (D166 guard)")

    lines = []
    A = lines.append
    A("# Table M — Family-stability tier assessment (registry artifact)")
    A("")
    A("**Authority:** `docs/analysis_registry_familyexpansion.md` §5–§6. Generated by "
      "`code/make_tableM_tiers.py` from `results/exM_suite_metrics.csv` + "
      "`results/exM_benchmark_matched_summary.csv` — never hand-edited.")
    A("")
    A("**Legend.** Per-test markers: ✓ = ready criterion met · ~ = provisional trigger · × = "
      "incidental trigger. Verdicts per registry §6 (all-ready-with-T7, otherwise provisional, or "
      "incidental on no-gain / tie collapse / thin footprint). τ = 10⁻⁶ noise floor. T7 = canonical "
      "span-matched random-suite benchmark (seed 42).")
    A("")
    A("| Suite | m | T1 2-D PCA (paired ratio [95% CI]) | T2 MDS (paired ratio [95% CI]) | T3 floor δ_fam | T4 3-D | T5 ties | T6 footprint (full r/p) | T7 exceeded | Verdict |")
    A("|---|---|---|---|---|---|---|---|---|---|")
    for r in suites:
        name = r["name"]
        m = r["m_params"]
        t = t7[name]
        t3_ok = f(r["med_fam_2d_pca"]) > TAU
        t5 = f(r["tie_rate"])
        t5_mark = "✓" if t5 < 0.10 else ("~" if t5 <= 0.50 else "×")
        full, fp = int(float(r["full_rows"])), int(float(r["full_papers"]))
        t6_mark = "✓" if (full >= 10 and fp >= 10) else ("~" if full >= 10 else "×")
        if str(r["reportable_3d"]).strip() == "True":
            r3 = f(r["raw_ratio_3d_pca"])
            t4 = f"reportable, {num(r['raw_ratio_3d_pca'])} " + ("✓" if r3 > 1 else "~")
        else:
            t4 = f"unreportable (m = {m}) ~"
        exc, nd = int(float(t["exceed_paired_nondeg"])), int(float(t["n_non_deg"]))
        t7_cell = f"{exc}/{nd} " + ("✓" if exc == 0 else "~")
        # The seven frozen families take their tier from results/family_tiers.csv
        # (code/family_tiers.py), which applies the Table 5 rubric as published.
        # The registry §6 combination below predates that reading of criterion 6
        # ("no collapse, or collapse above tau") and of criterion 7, and marked
        # three of the seven incidental, which would contradict the manuscript's
        # statement that all seven are provisional. The exploratory suites are
        # not families and keep the registry rule.
        verdict = frozen_tier.get(name) or registry_status(r, t)
        A(f"| `{name}` | {m} | {num(r['paired_ratio_2d_pca'])} "
          f"[{num(r['ci_low_2d_pca'])}, {num(r['ci_high_2d_pca'])}] {t1_mark(r)} | "
          f"{num(r['paired_ratio_mds'])} [{num(r['ci_low_mds'])}, {num(r['ci_high_mds'])}] {t2_mark(r)} | "
          f"{sci(r['med_fam_2d_pca'])} {'✓' if t3_ok else '~'} | {t4} | {pct(r['tie_rate'])}% {t5_mark} | "
          f"{full}/{fp} {t6_mark} | {t7_cell} | {verdict} |")
    A("")
    A("**Notes.** (1) **Zero suites reach *ready*** — failing T7 (any non-degenerate exceedance) or a "
      "structural criterion. (2) The verdicts for the seven frozen families are read from "
      "`results/family_tiers.csv` (`code/family_tiers.py`), which applies the Table 5 rubric as "
      "published; the exploratory suites use the registry §6 combination. The manuscript states "
      "that all seven families are provisional, none ready and none incidental, and this table agrees. "
      "The T7 column reports the paired-ratio exceedances of the matched benchmark, while the verdicts "
      "read the raw-ratio exceedances in `results/family_tiers.csv`, so the two metrics can disagree in "
      "direction (F6 aeration: 0 of 13 paired against 10 of 91 raw). The tier does not move either way, "
      "because F6 aeration is held at provisional by the floor test and the 3-D criterion. The "
      "F1a/F2 caption reconciliation of registry §10 was closed on 2026-10-21 on that basis; the "
      "verdicts below are the classification of record. (3) Best exploratory result on T7 is "
      "`F1_phys_nutr` (3/100), still above the Holm-adjusted threshold for the nine-candidate set "
      "(0.05/9 ≈ 0.0056). (4) This table is a registry artifact, not part of the submitted manuscript.")

    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    os.replace(tmp, OUT)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
